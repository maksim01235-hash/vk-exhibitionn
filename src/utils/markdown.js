/**
 * Утилита для рендеринга Markdown в HTML.
 * 
 * Использует библиотеку marked (подключена в index.html через CDN).
 * Если библиотека не загрузилась — fallback: экранирует HTML и заменяет
 * переносы строк на <br>, чтобы текст оставался читаемым.
 * 
 * Поддерживаемый синтаксис (GitHub Flavored Markdown):
 *   **жирный**, *курсив*, ~~зачёркнутый~~, `код`
 *   [ссылка](url), ![картинка](url)
 *   # Заголовок 1, ## Заголовок 2, ### Заголовок 3
 *   - маркированный список, 1. нумерованный список
 *   > цитата
 *   --- горизонтальная линия
 * 
 * При расширении можно добавить:
 *   — Поддержку HTML-тегов в Markdown (сейчас экранируются)
 *   — Подсветку синтаксиса для блоков кода
 *   — Кастомные рендереры (например, для вставки компонентов)
 */

// ═══════════════════════════════════════
// НАСТРОЙКИ MARKED
// ═══════════════════════════════════════

/**
 * Настройки для marked.parse().
 * 
 * breaks: true  — одиночный перенос строки внутри абзаца → <br>
 *   Без этого:   "строка1\nстрока2" → "строка1 строка2"
 *   С этим:      "строка1\nстрока2" → "строка1<br>строка2"
 * 
 * gfm: true     — GitHub Flavored Markdown (таблицы, списки задач, зачёркнутый)
 */
const MARKED_OPTIONS = {
  breaks: true,
  gfm: true,
};

/**
 * Рендерит Markdown-строку в HTML.
 * 
 * @param {string} text — сырой Markdown
 * @returns {string} HTML
 * 
 * @example
 *   renderMarkdown('**Жирный** и *курсив*')
 *   // → '<strong>Жирный</strong> и <em>курсив</em>'
 * 
 *   renderMarkdown('- Пункт 1\n- Пункт 2')
 *   // → '<ul><li>Пункт 1</li><li>Пункт 2</li></ul>'
 */
export function renderMarkdown(text) {
  if (!text) return '';

  // Основной путь: библиотека marked доступна
  if (typeof marked !== 'undefined') {
    return marked.parse(text, MARKED_OPTIONS);
  }

  // Запасной путь: marked не загрузился (офлайн, блокировщик рекламы)
  // Экранируем HTML и сохраняем переносы строк
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/\n/g, '<br>');
}